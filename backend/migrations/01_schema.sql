-- =========================
-- AGGREGATES & WEAKNESS SCORES
-- computed periodically (batch job) or on-demand via function
-- stores user's weakness score at subject/topic/chapter granularity
-- =========================
create table user_topic_stats (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references users(id) on delete cascade,
  topic_master_id uuid references topic_master(id) on delete set null,
  class int,                     -- redundant but handy
  subject text,
  chapter text,
  topic text,
  questions_asked int default 0, -- count of tutor questions from user about this topic
  quizzes_taken int default 0,
  avg_quiz_score numeric default 0, -- 0..100
  last_seen_at timestamptz,
  updated_at timestamptz default now(),
  unique (user_id, topic_master_id)
);

-- This table stores computed weakness (0=strong -> 100=weak)
create table user_topic_weakness (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references users(id) on delete cascade,
  topic_master_id uuid references topic_master(id) on delete set null,
  subject text,
  chapter text,
  topic text,
  weakness_score numeric not null check (weakness_score >= 0 and weakness_score <= 100),
  evidence_count int default 0,    -- how many signals contributed
  last_computed_at timestamptz default now(),
  note text,
  unique (user_id, topic_master_id)
);

create index on user_topic_weakness (user_id, weakness_score desc);

