/*
 recompute_user_topic_weakness:
  - aggregates quiz performance + tutor questions for user per topic_master
  - formula (example, tweak weights as you want):
      weakness_score = clamp( 0.7*(100 - avg_quiz_score) + 0.3*min(100, questions_asked * 10), 0, 100)
  - stores upsert into user_topic_weakness
*/
create or replace function recompute_user_topic_weakness(p_user_id uuid)
returns void language plpgsql as $$
declare
  rec record;
  v_weakness_score numeric;
  v_evidence_count int;
begin
  -- Aggregate quiz data per topic (subject, chapter, topic) using quizzes & quiz_attempts
  for rec in
    select
      tm.id as topic_master_id,
      coalesce(tm.curriculum_class, 0) as class,
      tm.subject,
      tm.chapter,
      tm.topic,
      coalesce(qs.quizzes_taken,0) as quizzes_taken,
      coalesce(qs.avg_quiz_score,0) as avg_quiz_score,
      coalesce(tm_qa.questions_asked,0) as questions_asked
    from topic_master tm
    left join (
      select q.topic, q.chapter, q.subject, count(distinct q.id) as quizzes_taken,
             avg(qa.score_percent) as avg_quiz_score
      from quizzes q
      join quiz_attempts qa on qa.quiz_id = q.id
      where q.user_id = p_user_id
      group by q.subject, q.chapter, q.topic
    ) qs on qs.topic = tm.topic and qs.chapter = tm.chapter and qs.subject = tm.subject
    left join (
      select tm2.topic, tm2.chapter, tm2.subject, count(*) as questions_asked
      from tutor_messages tm2msgs
      join topic_master tm2 on (tm2.topic = tm2msgs.detected_topic and tm2.chapter = tm2msgs.detected_chapter and tm2.subject = tm2msgs.detected_subject)
      where tm2msgs.user_id = p_user_id
      group by tm2.topic, tm2.chapter, tm2.subject
    ) tm_qa on tm_qa.topic = tm.topic and tm_qa.chapter = tm.chapter and tm_qa.subject = tm.subject
    where tm.subject is not null
  loop
    -- compute weakness score
    -- If no quizzes, avg_quiz_score will be 0; questions_asked will influence score
    -- weights: quiz component 0.7, question component 0.3
    -- question impact capped at 100 (e.g. >10 questions saturates)
    v_weakness_score := greatest(0, least(100,
      (0.7 * (100 - coalesce(rec.avg_quiz_score,0))) + (0.3 * least(100, (coalesce(rec.questions_asked,0) * 10)))
    ));
    
    v_evidence_count := coalesce(rec.quizzes_taken,0) + coalesce(rec.questions_asked,0);
    
    insert into user_topic_weakness (user_id, topic_master_id, subject, chapter, topic, weakness_score, evidence_count, last_computed_at)
    values (
      p_user_id,
      rec.topic_master_id,
      rec.subject,
      rec.chapter,
      rec.topic,
      v_weakness_score,
      v_evidence_count,
      now()
    )
    on conflict (user_id, topic_master_id) do update
    set weakness_score = excluded.weakness_score,
        evidence_count = excluded.evidence_count,
        last_computed_at = excluded.last_computed_at;
  end loop;
end;
$$;