/*
 compute_user_streak:
  - counts consecutive days up to current_date where study_activity exists for the user
  - returns integer days in current streak
*/
create or replace function compute_user_streak(p_user_id uuid)
returns int language plpgsql as $$
declare
  cur_date date := current_date;
  streak int := 0;
  d date;
begin
  -- loop backwards from today until a missing day
  d := cur_date;
  loop
    if exists (
      select 1 from study_activity
      where user_id = p_user_id
        and created_at::date = d
    ) then
      streak := streak + 1;
      d := d - interval '1 day';
    else
      exit;
    end if;
  end loop;

  -- update user_streaks table (upsert)
  insert into user_streaks (user_id, current_streak_days, last_activity_date, updated_at)
  values (p_user_id, streak, current_date, now())
  on conflict (user_id) do update
    set current_streak_days = excluded.current_streak_days,
        last_activity_date = excluded.last_activity_date,
        updated_at = now();

  return streak;
end;
$$;

