-- Shiksha-AI: Detailed Postgres Schema (Supabase)
-- Focus: users, AI tutor signals, planner, streaks, weak-topic detection
-- Paste into Supabase SQL editor. Requires pgcrypto for gen_random_uuid().
create extension if not exists "pgcrypto";

-- =========================
-- ENUMS
-- =========================
create type difficulty_enum as enum ('easy','medium','hard');
create type role_enum as enum ('user','assistant');
create type activity_enum as enum ('chat','quiz_attempt','plan_completed','task_completed','login');

-- =========================
-- CORE USER TABLES
-- =========================
create table users (
  id uuid primary key default gen_random_uuid(),
  email text unique,
  name text,
  created_at timestamptz default now()
);

create table user_profile (
  user_id uuid primary key references users(id) on delete cascade,
  class int not null check (class between 6 and 12),
  board text default 'CBSE',
  subjects text[] not null,                -- e.g. {'Maths','Science'}
  weak_topics text[] default '{}',         -- quick storage (human-readable) but we also compute structured weakness
  strong_topics text[] default '{}',
  target_exams text[] default '{}',        -- e.g. {'Boards','JEE'}
  daily_study_hours int default 1,
  timezone text default 'Asia/Kolkata',
  updated_at timestamptz default now()
);

-- =========================
-- NCERT / TOPIC MASTER
-- Canonical mapping of curriculum -> used by Tutor & Planner
-- =========================
create table topic_master (
  id uuid primary key default gen_random_uuid(),
  curriculum_class int not null check (curriculum_class between 6 and 12),
  board text not null default 'CBSE',
  subject text not null,                  -- e.g. 'Science'
  chapter text not null,                  -- e.g. 'Motion'
  chapter_order int default 0,
  topic text not null,                    -- more granular topic e.g. 'Newton's First Law'
  topic_order int default 0,
  source_file text,                        -- pointer to NCERT PDF path / filename
  source_page_range text,                  -- e.g. '12-18'
  created_at timestamptz default now(),
  unique(curriculum_class, board, subject, chapter, topic)
);

-- Optionally store chunk metadata for RAG (no vectors in PG)
create table ncert_chunks (
  id uuid primary key default gen_random_uuid(),
  topic_master_id uuid references topic_master(id) on delete set null,
  chunk_text text not null,
  token_count int,
  chunk_order int default 0,
  source text,                 -- original pdf page / filename
  external_vector_id text,     -- external vector DB ID if you use one
  created_at timestamptz default now()
);

-- =========================
-- TUTOR CHAT: sessions + messages
-- (store detected subject/topic info per message for signal extraction)
-- =========================
create table tutor_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references users(id) on delete cascade,
  started_at timestamptz default now(),
  last_active_at timestamptz default now()
);

create table tutor_messages (
  id uuid primary key default gen_random_uuid(),
  session_id uuid references tutor_sessions(id) on delete cascade,
  user_id uuid references users(id) on delete cascade,
  role role_enum not null,
  content text not null,
  detected_class int,           -- optional: class from detection pipeline (6..12)
  detected_subject text,        -- e.g. 'Science'
  detected_chapter text,        -- e.g. 'Motion'
  detected_topic text,          -- e.g. 'Newton First Law'
  detection_confidence numeric, -- 0..1 how confident the detector/LLM is
  answer_mode text,             -- 'simple','2-mark','5-mark','topper' for assistant messages
  created_at timestamptz default now()
);

-- Indexes to speed queries by topic and date
create index on tutor_messages (user_id);
create index on tutor_messages (detected_topic);
create index on tutor_messages (created_at);

-- =========================
-- QUIZZES + ATTEMPTS (planner signals)
-- =========================
create table quizzes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references users(id) on delete cascade,
  created_by text,               -- system / teacher / autogenerated
  subject text not null,
  topic text not null,
  chapter text,
  difficulty difficulty_enum default 'medium',
  total_questions int not null check (total_questions > 0),
  config jsonb default '{}' ,    -- store question prefs, e.g. {"num_mcq": 5}
  created_at timestamptz default now()
);

create table quiz_attempts (
  id uuid primary key default gen_random_uuid(),
  quiz_id uuid references quizzes(id) on delete cascade,
  user_id uuid references users(id) on delete cascade,
  correct_answers int not null check (correct_answers >= 0),
  total_questions int not null check (total_questions > 0),
  time_taken_seconds int default 0,
  score_percent numeric generated always as ( (correct_answers::numeric / total_questions::numeric) * 100 ) stored,
  attempt_meta jsonb default '{}', -- store per-question stats if needed
  created_at timestamptz default now()
);

create index on quiz_attempts (user_id);
create index on quiz_attempts (created_at);

-- =========================
-- STUDY PLANS + PLAN TASKS (planner output + per-task status)
-- =========================
create table study_plans (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references users(id) on delete cascade,
  plan_date date not null,               -- the date this plan is for
  generated_by text default 'system',    -- 'system' or 'teacher'
  plan_meta jsonb default '{}',          -- high-level metadata
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  unique(user_id, plan_date)
);

-- plan tasks are individual items in a day's plan
create table plan_tasks (
  id uuid primary key default gen_random_uuid(),
  study_plan_id uuid references study_plans(id) on delete cascade,
  user_id uuid references users(id) on delete cascade,
  task_type text not null,               -- 'study','quiz','revision','watch_video'
  subject text,
  chapter text,
  topic text,
  duration_min int default 0,
  quiz_id uuid references quizzes(id) on delete set null,
  scheduled_at timestamptz,              -- scheduled time in user's timezone
  status text default 'pending',         -- 'pending','in_progress','completed','skipped'
  completed_at timestamptz,
  created_at timestamptz default now()
);

create index on plan_tasks (user_id);
create index on plan_tasks (study_plan_id);

